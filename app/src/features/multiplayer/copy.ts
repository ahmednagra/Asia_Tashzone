export function errorMessage(code: string | null | undefined): string {
  return (code && copy.errors[code]) || copy.errors.ERROR!;
}

function ordinal(n: number): string {
  const v = n % 100;
  return `${n}${["th", "st", "nd", "rd"][(v - 20) % 10] ?? ["th", "st", "nd", "rd"][v] ?? "th"}`;
}
